def panel_sources(species_table: Path = SPECIES_TABLE, manifest_path: Path = MANIFEST,
                  sources_path: Path = PANEL_SOURCES) -> tuple[list[dict], dict]:
    """One dict per panel species (code, upid, filename, url, sha256) in species-table order, and the
    sources file (expected panel.fasta checksum)."""
    import pandas as pd

    tab = pd.read_csv(species_table, sep="\t", dtype=str)
    entries = {e["id"]: e for e in yaml.safe_load(Path(manifest_path).read_text())["entries"]}
    src = json.loads(Path(sources_path).read_text())
    core_url = entries[src["qfo_manifest_id"]]["url"]
    core_url = core_url if core_url.endswith("/") else core_url + "/"
    out = []
    for r in tab.itertuples(index=False):
        if r.selection_group == "core":
            fn = f"{r.upid}_{r.taxid}.fasta.gz"
            rec = src["files"].get(fn)
            if rec is None:
                raise SetupError(f"{fn} ({r.code}) has no checksum in {sources_path}")
            out.append({"code": r.code, "upid": r.upid, "filename": fn, "url": core_url + fn, "sha256": rec["sha256"]})
        else:
            e = entries.get(f"panel_extra_{r.upid}")
            if e is None or not e.get("sha256"):
                raise SetupError(f"panel species {r.code} ({r.upid}) has no manifest entry with a sha256")
            out.append({"code": r.code, "upid": r.upid, "filename": e["filename"], "url": e["url"], "sha256": e["sha256"]})
    return out, src


def _read_fasta_gz(path: Path):
    """(accession, sequence) per record; same parsing as scripts/data/build_panel.py."""
    import gzip

    acc, buf = None, []
    with gzip.open(path, "rt") as fh:
        for line in fh:
            if line.startswith(">"):
                if acc is not None:
                    yield acc, "".join(buf)
                parts = line[1:].split()[0].split("|")
                acc, buf = parts[1] if len(parts) > 1 else parts[0], []
            else:
                buf.append(line.strip().upper())
    if acc is not None:
        yield acc, "".join(buf)


def assemble_panel(sources: list[dict], downloads: Path, fasta_out: Path, index_out: Path | None = None) -> dict:
    """panel.fasta with headers '<code>|<index>' (0-based index in file order within the species), written
    atomically in species-table order, exactly as scripts/data/build_panel.py assemble."""
    fasta_out.parent.mkdir(parents=True, exist_ok=True)
    part = fasta_out.with_name(fasta_out.name + ".part")
    ipart = None if index_out is None else index_out.with_name(index_out.name + ".part")
    counts = {}
    with open(part, "w") as fa, (open(ipart, "w") if ipart else open(os.devnull, "w")) as ix:
        ix.write("code\tindex\taccession\n")
        for s in sources:
            i = 0
            for acc, seq in _read_fasta_gz(downloads / s["filename"]):
                seq = seq.replace("*", "")
                if not seq:
                    continue
                fa.write(f">{s['code']}|{i}\n")
                for k in range(0, len(seq), 60):
                    fa.write(seq[k:k + 60] + "\n")
                ix.write(f"{s['code']}\t{i}\t{acc}\n")
                i += 1
            counts[s["code"]] = i
    part.replace(fasta_out)
    if ipart is not None:
        ipart.replace(index_out)
    return counts


def write_panel_config(dd: Path, base_config: str | Path | None = None,
                       species_table: str | Path | None = None) -> Path:
    """config/panel.yaml with the panel FASTA, databases and hit cache moved under ``<data>/panel``."""
    base = Path(dd) / "panel"
    pcfg = panel_mod.load_panel_config(base_config)
    pcfg["panel"]["fasta"] = str(base / "panel.fasta")
    pcfg["panel"]["index"] = str(base / "panel_index.tsv")
    pcfg["panel"]["species_table"] = str(panel_mod._abs(species_table or pcfg["panel"]["species_table"]))
    pcfg["tier_b"]["db_dir"] = str(base / "db")
    pcfg["tier_b"]["cache_dir"] = str(base / "hits")
    p = panel_config_path(dd)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(yaml.safe_dump(pcfg, sort_keys=False))
    return p


def setup_panel(dd: Path, threads: int = 1, *, downloader: Downloader | None = None, species_table: Path | None = None,
                manifest_path: Path | None = None, sources_path: Path | None = None,
                base_config: Path | None = None, keep_downloads: bool = False, min_free_gb: float = MIN_FREE_GB_PANEL) -> dict:
    """Download (checksummed), assemble and index the reference panel. Idempotent."""
    t0 = time.time()
    base = Path(dd) / "panel"
    st = Path(species_table or SPECIES_TABLE)
    sources, src = panel_sources(st, Path(manifest_path or MANIFEST), Path(sources_path or PANEL_SOURCES))
    fasta_out, index_out = base / "panel.fasta", base / "panel_index.tsv"
    expected = src.get("panel_fasta_sha256")
    log_ = {"n_species": len(sources), "downloaded": [], "present": []}
    if fasta_out.exists() and expected and _sha256_file(fasta_out) == expected:
        log_["panel_fasta"] = "present"
    else:
        _check_free(base, min_free_gb)
        dl = base / "downloads"
        for s in sources:
            status = fetch_verified(s["url"], dl / s["filename"], s["sha256"], downloader)
            log_["downloaded" if status == "downloaded" else "present"].append(s["code"])
        counts = assemble_panel(sources, dl, fasta_out, index_out)
        got = _sha256_file(fasta_out)
        if expected and got != expected:
            fasta_out.unlink()
            raise SetupError(f"assembled panel.fasta checksum {got[:16]} != expected {expected[:16]} "
                             f"(source proteome contents differ from the pinned ones)")
        log_["panel_fasta"] = "assembled"
        log_["n_proteins"] = int(sum(counts.values()))
        if not keep_downloads:
            shutil.rmtree(dl, ignore_errors=True)
    pcp = write_panel_config(dd, base_config, st)
    pcfg = panel_mod.load_panel_config(pcp)
    ccfg = load_yaml(CONFIG_DIR / "caller.yaml")
    wd = Path(tempfile.mkdtemp(prefix="slparalog_setup_"))
    try:
        mm = search.MMseqs(binary=search.resolve_binary(ccfg), threads=int(threads), workdir=wd)
        stamp = panel_mod.build_dbs(pcfg, mm)
    finally:
        shutil.rmtree(wd, ignore_errors=True)
    log_.update({"panel_config": str(pcp), "db_stamp": {k: stamp[k] for k in ("panel_fasta_sha256", "mmseqs_sha256")},
                 "elapsed_s": round(time.time() - t0, 1)})
    return log_



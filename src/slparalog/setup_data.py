Downloader = Callable[[str, Path], None]


def http_download(url: str, dest: Path, retries: int = 4) -> None:
    """Stream ``url`` to ``dest`` (same checks as scripts/data/download.py: status 200, complete length,
    no HTML challenge page saved as data). Raises SetupError."""
    last: Exception | None = None
    for attempt in range(1, retries + 1):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA})
            with urllib.request.urlopen(req, timeout=120) as r, open(dest, "wb") as fh:
                n = 0
                while chunk := r.read(1 << 20):
                    fh.write(chunk)
                    n += len(chunk)
                clen = r.headers.get("Content-Length")
                if clen and r.headers.get("Content-Encoding") is None and int(clen) != n:
                    raise SetupError(f"truncated: got {n} of {clen} bytes")
            if n == 0:
                raise SetupError("empty response")
            with open(dest, "rb") as fh:
                head = fh.read(512).lstrip().lower()
            if head.startswith((b"<!doctype html", b"<html")):
                raise SetupError("server returned an HTML page instead of data")
            return
        except (OSError, SetupError) as e:
            last = e
            dest.unlink(missing_ok=True)
            time.sleep(2 * attempt)
    raise SetupError(f"download failed: {url}: {last}")


def fetch_verified(url: str, dest: Path, sha256: str, downloader: Downloader | None = None) -> str:
    """Make ``dest`` a file with checksum ``sha256``. Returns ``"present"`` or ``"downloaded"``."""
    if dest.exists() and _sha256_file(dest) == sha256:
        return "present"
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_name(dest.name + ".part")
    tmp.unlink(missing_ok=True)
    (downloader or http_download)(url, tmp)
    got = _sha256_file(tmp)
    if got != sha256:
        tmp.unlink(missing_ok=True)
        raise SetupError(f"checksum mismatch for {url}: got {got}, expected {sha256}")
    tmp.replace(dest)
    return "downloaded"



def setup_model(dd: Path, src: str | Path, allow_sklearn_mismatch: bool = False) -> dict:
    """Validate the artifact at ``src`` (registry hash, features, checksum) and copy it to
    ``<data>/models/<model_id>``; it becomes the default model. Idempotent."""
    src = Path(src).expanduser()
    try:
        m = load_model(src, allow_sklearn_mismatch=allow_sklearn_mismatch)
    except ModelError as e:
        raise SetupError(f"refusing to install {src}: {e}") from e
    dest = Path(dd) / "models" / m.model_id
    status = "present"
    if not (dest / "model.json").exists() or read_meta(dest).get("model_sha256") != m.meta["model_sha256"]:
        tmp = dest.with_name(dest.name + ".part")
        shutil.rmtree(tmp, ignore_errors=True)
        tmp.mkdir(parents=True)
        for f in ("model.joblib", "model.json"):
            shutil.copy2(src / f, tmp / f)
        shutil.rmtree(dest, ignore_errors=True)
        tmp.replace(dest)
        status = "installed"
    (Path(dd) / "models" / "CURRENT").write_text(m.model_id + "\n")
    return {"model_id": m.model_id, "status": status, "path": str(dest)}

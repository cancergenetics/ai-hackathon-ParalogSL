def _hf_snapshot_download(repo_id: str, revision: str, cache_dir: Path, files: list[str]) -> None:
    try:
        from huggingface_hub import snapshot_download
    except ImportError as e:  # pragma: no cover
        raise SetupError("huggingface_hub is needed to fetch the ESM-2 weights: pip install huggingface_hub") from e
    snapshot_download(repo_id=repo_id, revision=revision, cache_dir=str(cache_dir), allow_patterns=files)


def _verify_snapshot(snap: Path, files: dict[str, str]) -> list[str]:
    """Names of files that are missing or whose sha256 differs."""
    bad = []
    for name, sha in files.items():
        p = snap / name
        if not p.exists() or _sha256_file(p) != sha:
            bad.append(name)
    return bad


def setup_plm(dd: Path, model_key: str | None = None, *, snapshot_download: Callable | None = None,
              weights_path: Path | None = None, plm_config: dict | None = None,
              min_free_gb: float = MIN_FREE_GB_PLM) -> dict:
    """Fetch the ESM-2 files at the revision pinned in config/plm.yaml and verify their sha256. Idempotent."""
    from . import plm  # torch-free at module level

    cfg = plm_config or plm.load_plm_config()
    key = model_key or cfg["default_model"]
    spec = cfg["models"][key]
    wj = json.loads(Path(weights_path or PLM_WEIGHTS).read_text())
    if key not in wj:
        raise SetupError(f"{PLM_WEIGHTS.name} has no checksums for {key}")
    if wj[key]["revision"] != spec["revision"]:
        raise SetupError(f"{PLM_WEIGHTS.name} is for revision {wj[key]['revision']}, config/plm.yaml pins {spec['revision']}")
    files = wj[key]["files"]
    hf = Path(dd) / "plm" / "hf"
    snap = hf / "hub" / ("models--" + spec["hf_id"].replace("/", "--")) / "snapshots" / spec["revision"]
    status = "present"
    if _verify_snapshot(snap, files):
        _check_free(hf, min_free_gb)
        (snapshot_download or _hf_snapshot_download)(spec["hf_id"], spec["revision"], hf / "hub", sorted(files))
        bad = _verify_snapshot(snap, files)
        if bad:
            raise SetupError(f"ESM-2 files failed verification after download: {bad}")
        status = "downloaded"
    rec_path = Path(dd) / "plm" / "PLM_SETUP.json"
    rec = json.loads(rec_path.read_text()) if rec_path.exists() else {}
    rec[key] = {"hf_id": spec["hf_id"], "revision": spec["revision"], "files": files,
                "verified_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")}
    rec_path.parent.mkdir(parents=True, exist_ok=True)
    rec_path.write_text(json.dumps(rec, indent=1))
    return {"model": key, "revision": spec["revision"], "status": status, "hf_home": str(hf)}



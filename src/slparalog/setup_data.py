SPECIES_TABLE = CONFIG_DIR / "panel_species.tsv"
MIN_FREE_GB_PANEL = 8.0
MIN_FREE_GB_PLM = 2.0
UA = "slparalog-setup/1.0 (academic research; urllib)"


class SetupError(RuntimeError):
    pass


# ----------------------------------------------------------------------------------------------
# locations
# ----------------------------------------------------------------------------------------------

def data_dir(arg: str | Path | None = None) -> Path:
    return Path(arg or os.environ.get(ENV_VAR) or DEFAULT_DIR).expanduser()


def panel_config_path(dd: Path) -> Path:
    return Path(dd) / "panel" / "panel.yaml"


def plm_home(dd: Path) -> Path | None:
    """HF_HOME of the set-up weights, or None if ``setup --plm`` has not run under ``dd``."""
    rec = Path(dd) / "plm" / "PLM_SETUP.json"
    return Path(dd) / "plm" / "hf" if rec.exists() else None


def resolve_model(arg: str | Path | None, dd: Path) -> Path:
    """``arg`` as a model directory, or as a model id under ``<data>/models``; default: the model last set up."""
    models = Path(dd) / "models"
    if arg:
        p = Path(arg).expanduser()
        if (p / "model.json").exists():
            return p
        if (models / str(arg) / "model.json").exists():
            return models / str(arg)
        raise SetupError(f"no model at {p} or {models / str(arg)} (a model directory holds model.json + model.joblib)")
    cur = models / "CURRENT"
    if cur.exists():
        p = models / cur.read_text().strip()
        if (p / "model.json").exists():
            return p
    raise SetupError("no model given: pass --model DIR, or install one with `slparalog setup --model DIR`")


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _check_free(path: Path, need_gb: float) -> None:
    path.mkdir(parents=True, exist_ok=True)
    free = shutil.disk_usage(path).free / 1e9
    if free < need_gb:
        raise SetupError(f"only {free:.1f} GB free under {path}; need about {need_gb:.0f} GB")



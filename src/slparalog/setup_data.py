"""``slparalog setup``: fetch and build what ``predict`` needs under one data directory.

Data directory: ``--data-dir`` > ``$SLPARALOG_DATA`` > ``~/.slparalog``. Layout::

    <data>/panel/downloads/*.fasta.gz   verified source proteomes (removed after a verified assembly)
    <data>/panel/panel.fasta            assembled panel, headers '<code>|<index>' (sha256 checked)
    <data>/panel/db/<code>/             per-species MMseqs2 databases (panel.build_dbs, stamped)
    <data>/panel/hits/                  per-(query proteome, settings) panel-hit cache
    <data>/panel/panel.yaml             config/panel.yaml with the paths above
    <data>/plm/hf/                      HF cache with the ESM-2 weights at the pinned revision
    <data>/models/<model_id>/           model artifacts (copied from a local path)

Sources and checksums: the species table ``config/panel_species.tsv`` (one row per panel species), the
gap-fill entries (URL + sha256) of ``config/data_manifest.yaml`` and, for the QfO core proteomes (whose
manifest entry is a bulk local record), the per-file checksums of ``config/panel_sources.json``;
the PLM files and checksums of ``config/plm_weights.json`` (revision pinned in ``config/plm.yaml``). Both
JSON files are generated by ``scripts/data/make_setup_checksums.py`` from the verified local copies.

Every download goes to ``<name>.part`` and is renamed only after its sha256 matches. Re-running is
idempotent: verified files are skipped, an assembled panel with the expected checksum short-circuits the
panel download, and the MMseqs2 databases are rebuilt only if their stamp is stale. The MMseqs2 binary
(``bin/mmseqs``, pinned in ``config/tools.yaml``) is not fetched here.
"""


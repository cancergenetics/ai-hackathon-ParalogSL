#!/usr/bin/env python
"""Generate the checksum files read by ``slparalog setup`` from the verified local copies.

  config/panel_sources.json  per-file sha256 of the QfO core proteomes (data/raw/qfo/SHA256SUMS.txt) and the sha256
                             of the assembled data/interim/panel/panel.fasta (recomputed here and compared with
                             results/data/panel.json)
  config/plm_weights.json    per PLM model of config/plm.yaml: pinned revision and sha256 of every file of the cached
                             snapshot under models_cache/hf (skipped for models that are not cached)

Run (project venv): .venv/bin/python scripts/data/make_setup_checksums.py
"""
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from manifest_io import ROOT, sha256_file  # noqa: E402

import yaml  # noqa: E402


def main():
    qfo = {}
    for line in open(os.path.join(ROOT, "data/raw/qfo/SHA256SUMS.txt")):
        if line.strip():
            sha, fn = line.split()
            qfo[fn] = {"sha256": sha, "bytes": os.path.getsize(os.path.join(ROOT, "data/raw/qfo", fn))}
    panel_json = json.load(open(os.path.join(ROOT, "results/data/panel.json")))
    fasta_sha = sha256_file(os.path.join(ROOT, "data/interim/panel/panel.fasta"))
    assert fasta_sha == panel_json["panel_fasta_sha256"], "panel.fasta differs from results/data/panel.json"
    out = {"qfo_manifest_id": "qfo_2026_02",
           "note": "sha256 of QfO 2026_02 core proteome files (URL = manifest entry qfo_2026_02 url + filename) and of the assembled panel.fasta; "
                   "generated by scripts/data/make_setup_checksums.py",
           "panel_fasta_sha256": fasta_sha, "n_species": panel_json["n_species"], "n_proteins": panel_json["n_proteins"],
           "files": dict(sorted(qfo.items()))}
    json.dump(out, open(os.path.join(ROOT, "config/panel_sources.json"), "w"), indent=1)
    print(f"panel_sources.json: {len(qfo)} core files, panel.fasta {fasta_sha[:16]}")

    cfg = yaml.safe_load(open(os.path.join(ROOT, "config/plm.yaml")))
    plm = {}
    for key, spec in cfg["models"].items():
        snap = os.path.join(ROOT, cfg["hf_home"], "hub", "models--" + spec["hf_id"].replace("/", "--"), "snapshots", spec["revision"])
        if not os.path.isdir(snap):
            print(f"[skip] {key}: snapshot not cached")
            continue
        files = {fn: sha256_file(os.path.join(snap, fn)) for fn in sorted(os.listdir(snap))}
        plm[key] = {"hf_id": spec["hf_id"], "revision": spec["revision"], "files": files}
        print(f"plm_weights.json: {key} {len(files)} files")
    json.dump(plm, open(os.path.join(ROOT, "config/plm_weights.json"), "w"), indent=1)


if __name__ == "__main__":
    main()

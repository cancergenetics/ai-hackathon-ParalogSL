#!/usr/bin/env python
"""Reference panel = QfO 2026_02 core + gap-fill proteomes chosen by the written rule in config/panel.yaml
(DESIGN v3 §2.2; reviews/round2/algorithms_comparative.md change 8, logic of the reviewer's tested select.py).

Run (project venv):  .venv/bin/python scripts/data/build_panel.py {snapshot|select|download|assemble|all} [--refresh]

  snapshot  query the UniProt REST proteome endpoint once per candidate pool (+ the core UPIDs), save the JSON bodies, the
            response headers (x-uniprot-release must equal config uniprot_release) and SHA256SUMS.txt under
            data/raw/panel_meta/. Skipped if a snapshot exists (use --refresh to re-query; refuses a different release).
  select    verify the snapshot checksums, apply the rule, write results/data/panel_selection.{json,tsv} and (re)generate the
            panel_meta / panel_extra entries in config/data_manifest.yaml.
  download  run scripts/data/download.py --only panel_meta panel_extra (checksums go to the lock file and SOURCE.json), then
            write each file's sha256 into its manifest entry (download.py verifies it on every later run).
  assemble  write data/interim/panel/panel.fasta (headers '<code>|<index>'; no names/annotations), panel_index.tsv,
            config/panel_species.tsv and results/data/panel.json.
"""
import argparse, collections, datetime, gzip, hashlib, json, os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from manifest_io import ROOT, MANIFEST, sha256_file, load_manifest  # noqa: E402

CFG_PATH = os.path.join(ROOT, "config", "panel.yaml")
RES_DIR = os.path.join(ROOT, "results", "data")
GEN_START = "  # >>> generated by scripts/data/build_panel.py select/download (panel_meta + panel_extra); do not edit by hand >>>"
GEN_END = "  # <<< end of build_panel.py block <<<"
UA = "sl_run2-data-acquisition/1.0 (academic research; python-requests)"


def P(rel):
    return os.path.join(ROOT, rel)


def load_cfg(path=CFG_PATH):
    import yaml
    with open(path) as f:
        return yaml.safe_load(f)


def now():
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def read_core(cfg):
    rows = []
    with open(P(cfg["core"]["species_list"])) as f:
        for line in f:
            upid, taxid, code, n, name = line.rstrip("\n").split("\t")
            rows.append({"upid": upid, "taxid": taxid, "code": None if code in ("", "None") else code, "n": int(n), "name": name})
    return rows


# ----------------------------------------------------------------------------------------------------------- snapshot
def rest_query(cfg, query):
    import requests
    s = cfg["snapshot"]
    r = requests.get(s["endpoint"], params={"query": query, "fields": s["fields"], "format": "json"},
                     headers={"User-Agent": UA}, timeout=(30, 600))
    r.raise_for_status()
    rel = r.headers.get("x-uniprot-release")
    if rel != cfg["uniprot_release"]:
        raise SystemExit(f"UniProt REST serves release {rel}, config pins {cfg['uniprot_release']}; refusing to mix releases")
    return r.content, {k: r.headers.get(k) for k in ("x-uniprot-release", "x-uniprot-release-date", "x-api-deployment-date", "date")}, r.url


def snapshot(cfg, refresh=False):
    d = P(cfg["snapshot"]["dir"])
    meta_path = os.path.join(d, "SNAPSHOT.json")
    if os.path.exists(meta_path) and not refresh:
        print(f"[snapshot] exists ({meta_path}); not re-querying (use --refresh)")
        return
    os.makedirs(d, exist_ok=True)
    jobs = [(f"ref_{name}_{taxid}.json", f"(proteome_type:REFERENCE) AND (taxonomy_id:{taxid})")
            for name, taxid in cfg["snapshot"]["queries"].items()]
    core = read_core(cfg)
    jobs.append(("core_qfo_upids.json", " OR ".join(f"upid:{c['upid']}" for c in core)))
    meta = {"uniprot_release_pinned": cfg["uniprot_release"], "retrieved": now(), "endpoint": cfg["snapshot"]["endpoint"],
            "fields": cfg["snapshot"]["fields"], "files": []}
    for fn, q in jobs:
        body, hdr, url = rest_query(cfg, q)
        js = json.loads(body)
        with open(os.path.join(d, fn), "wb") as f:
            f.write(body)
        meta["files"].append({"filename": fn, "query": q, "url": url, "headers": hdr, "n_results": len(js["results"]),
                              "sha256": hashlib.sha256(body).hexdigest(), "bytes": len(body)})
        print(f"[snapshot] {fn}: {len(js['results'])} proteomes, release {hdr['x-uniprot-release']}")
    with open(meta_path, "w") as f:
        json.dump(meta, f, indent=1)
    write_sums(d)


def write_sums(d):
    files = sorted(x for x in os.listdir(d) if x.endswith(".json") and x != "SOURCE.json")
    with open(os.path.join(d, "SHA256SUMS.txt"), "w") as f:
        for x in files:
            f.write(f"{sha256_file(os.path.join(d, x))}  {x}\n")


def verify_sums(d):
    bad = []
    for line in open(os.path.join(d, "SHA256SUMS.txt")):
        sha, fn = line.split()
        if sha256_file(os.path.join(d, fn)) != sha:
            bad.append(fn)
    if bad:
        raise SystemExit(f"snapshot checksum mismatch: {bad}")


# ------------------------------------------------------------------------------------------------------------- select
def parse_record(r):
    """UniProt proteome JSON record -> flat dict (BUSCO percentages are None when no BUSCO report)."""
    b = (r.get("proteomeCompletenessReport") or {}).get("buscoReport")
    lin = {x["rank"]: x["scientificName"] for x in r.get("taxonLineage", [])}
    out = {"id": r["id"], "name": r["taxonomy"]["scientificName"], "tax": str(r["taxonomy"]["taxonId"]),
           "mnemonic": r["taxonomy"].get("mnemonic"), "n": r.get("proteinCount", 0), "lin": lin,
           "linall": [x["scientificName"] for x in r.get("taxonLineage", [])], "S": None, "D": None, "F": None}
    if b and b.get("total"):
        out.update(S=100 * b["completeSingle"] / b["total"], D=100 * b["completeDuplicated"] / b["total"],
                   F=100 * b["fragmented"] / b["total"], lineage_db=b.get("lineageDb"))
    return out


def in_clade(x, c):
    if any(x["lin"].get(rank) in names for rank, names in (c.get("rank_in") or {}).items()):
        return True
    return any(n in x["linall"] for n in (c.get("lineage_any") or []))


def select_rule(allp, core_ids, core_tax, cfg):
    """Exact port of the reviewer's select.py. allp: {upid: record}. -> (selected [(clade, ladder_step, record)], log)."""
    fl = cfg["filters"]
    corep = [allp[i] for i in core_ids if i in allp]
    sel, log = [], []
    for c in cfg["clades"]:
        unit, quota = c["unit"], c["quota"]
        members = [x for x in allp.values() if in_clade(x, c)]
        no_busco = [x for x in members if x["S"] is None]
        cand = [x for x in members if x["S"] is not None and x["id"] not in core_ids and x["tax"] not in core_tax
                and x["n"] <= fl["max_protein_count"] and x["D"] <= fl["max_busco_duplicated_pct"]]
        used = set(c.get("exclude_units") or []) | {x["lin"].get(unit) for x in corep if in_clade(x, c)}
        for step, (smin, fmax) in enumerate(fl["ladder"]):
            ok = [x for x in cand if x["S"] >= smin and x["F"] <= fmax]
            best = {}
            for x in sorted(ok, key=lambda x: (-x["S"], x["F"], x["id"])):
                u = x["lin"].get(unit, "?")
                if u in used or u in best:
                    continue
                best[u] = x
            picks = list(best.values())[:quota]
            if len(picks) >= quota or step == len(fl["ladder"]) - 1:
                break
        log.append({"clade": c["name"], "n_in_pool": len(members), "n_without_busco": len(no_busco), "n_candidates": len(cand),
                    "units_excluded": sorted(u for u in used if u), "ladder_step_used": [smin, fmax],
                    "n_passing_at_step": len(ok), "n_units_available": len(best), "quota": quota, "n_selected": len(picks),
                    "quota_met": len(picks) >= quota})
        sel += [(c["name"], [smin, fmax], x) for x in picks]
    ids = [x["id"] for _, _, x in sel]
    assert len(ids) == len(set(ids)), "a proteome was selected by two clades"
    return sel, log


def load_snapshot(cfg):
    d = P(cfg["snapshot"]["dir"])
    verify_sums(d)
    meta = json.load(open(os.path.join(d, "SNAPSHOT.json")))
    pools, core_meta = {}, {}
    for f in meta["files"]:
        recs = [parse_record(r) for r in json.load(open(os.path.join(d, f["filename"])))["results"]]
        if f["filename"].startswith("core_"):
            core_meta = {x["id"]: x for x in recs}
        else:
            for x in recs:
                pools[x["id"]] = x
    return meta, pools, core_meta


def manifest_entries(cfg, sel, shas=None):
    shas = shas or {}
    ent = [{"id": "panel_meta_2026_03", "group": "panel_meta", "type": "local", "path": cfg["snapshot"]["dir"],
            "checksums_file": cfg["snapshot"]["dir"] + "/SHA256SUMS.txt",
            "description": "UniProt REST proteome-metadata snapshot (JSON + response headers in SNAPSHOT.json) used to select the gap-fill panel proteomes",
            "url": cfg["snapshot"]["endpoint"], "filename": "*.json", "license": "CC BY 4.0 (UniProt)", "doi": "10.1093/nar/gkae1010",
            "used_for": "reference panel selection (config/panel.yaml rule); metadata only, never a feature", "committed": "no (regenerable)",
            "version": f"UniProt {cfg['uniprot_release']}", "notes": "Written by scripts/data/build_panel.py snapshot; selection reads only these files."}]
    for clade, _, x in sel:
        fn = f"{x['id']}_{x['tax']}.fasta.gz"
        e = {"id": f"panel_extra_{x['id']}", "group": "panel_extra",
             "description": f"UniProt reference proteome {x['id']} ({x['name']}, taxid {x['tax']}): canonical FASTA; gap-fill clade '{clade}'",
             "url": cfg["gap_fill_fasta"]["url"].format(upid=x["id"], taxid=x["tax"]), "filename": fn,
             "license": "CC BY 4.0 (UniProt)", "doi": "10.1093/nar/gkae1010",
             "used_for": "reference panel (homology search targets; gap-fill, config/panel.yaml)", "committed": "no (regenerable)",
             "version": f"UniProt {cfg['uniprot_release']}", "release_check": cfg["uniprot_release"], "notes": ""}
        if shas.get(e["id"]):
            e["sha256"] = shas[e["id"]]
        ent.append(e)
    return ent


def write_manifest_block(entries, path=MANIFEST):
    lines = [GEN_START]
    for e in entries:
        first = True
        for k, v in e.items():
            lines.append(("  - " if first else "    ") + f"{k}: {json.dumps(v, ensure_ascii=False)}")
            first = False
    lines.append(GEN_END)
    block = "\n".join(lines)
    txt = open(path).read()
    if GEN_START in txt:
        txt = re.sub(re.escape(GEN_START) + r".*?" + re.escape(GEN_END), lambda m: block, txt, flags=re.S)
    else:
        txt = txt.rstrip("\n") + "\n" + block + "\n"
    with open(path, "w") as f:
        f.write(txt)
    load_manifest(path)  # parse check


def select(cfg):
    meta, pools, core_meta = load_snapshot(cfg)
    core = read_core(cfg)
    core_ids, core_tax = {c["upid"] for c in core}, {c["taxid"] for c in core}
    sel, log = select_rule(pools, core_ids, core_tax, cfg)
    os.makedirs(RES_DIR, exist_ok=True)
    cols = ["clade", "ladder_S_min", "ladder_F_max", "upid", "taxid", "name", "mnemonic", "order", "family", "genus",
            "n_proteins", "busco_S", "busco_D", "busco_F"]
    rows = [[c, st[0], st[1], x["id"], x["tax"], x["name"], x["mnemonic"], x["lin"].get("order", "?"), x["lin"].get("family", "?"),
             x["lin"].get("genus", "?"), x["n"], round(x["S"], 2), round(x["D"], 2), round(x["F"], 2)] for c, st, x in sel]
    with open(os.path.join(RES_DIR, "panel_selection.tsv"), "w") as f:
        f.write("\t".join(cols) + "\n")
        for r in rows:
            f.write("\t".join(map(str, r)) + "\n")
    out = {"uniprot_release": meta["files"][0]["headers"]["x-uniprot-release"], "snapshot_retrieved": meta["retrieved"],
           "snapshot_sha256": {f["filename"]: f["sha256"] for f in meta["files"]},
           "n_core_species": len(core), "n_core_proteins": sum(c["n"] for c in core),
           "n_gap_fill_species": len(sel), "n_gap_fill_proteins_metadata": sum(x["n"] for _, _, x in sel),
           "n_panel_species": len(core) + len(sel), "n_panel_proteins_metadata": sum(c["n"] for c in core) + sum(x["n"] for _, _, x in sel),
           "clades": log, "selected": [dict(zip(cols, r)) for r in rows],
           "known_gaps": "no gymnosperm or lycophyte proteome passes the quality filters (not a clade in the rule)",
           "script": "scripts/data/build_panel.py select", "config_sha256": sha256_file(CFG_PATH)}
    with open(os.path.join(RES_DIR, "panel_selection.json"), "w") as f:
        json.dump(out, f, indent=1)
    write_manifest_block(manifest_entries(cfg, sel))
    for r in rows:
        print(f"{r[0]:28s} S>={r[1]} {r[3]} {r[5][:36]:36s} {r[7][:16]:16s} {r[8][:18]:18s} n={r[10]:6d} S={r[11]} D={r[12]} F={r[13]}")
    print(f"gap-fill species {len(sel)}, proteins {out['n_gap_fill_proteins_metadata']}; panel {out['n_panel_species']} species, "
          f"{out['n_panel_proteins_metadata']} proteins (metadata counts)")
    return sel


# ----------------------------------------------------------------------------------------------------------- download
def download(cfg):
    import shutil
    free = shutil.disk_usage(ROOT).free / 1e9
    print(f"[download] free disk {free:.0f} GB")
    meta, pools, _ = load_snapshot(cfg)
    sel_ids = [r["upid"] for r in json.load(open(os.path.join(RES_DIR, "panel_selection.json")))["selected"]]
    est = sum(pools[i]["n"] for i in sel_ids) * 250 / 1e9  # ~250 B per gzipped protein, generous
    if free < 25 + est:
        raise SystemExit("not enough free disk")
    rc = subprocess.call([sys.executable, os.path.join(ROOT, "scripts", "data", "download.py"), "--only", "panel_meta", "panel_extra"])
    if rc != 0:
        raise SystemExit(f"download.py exited {rc}")
    src = json.load(open(P(os.path.join(cfg["gap_fill_fasta"]["dir"], "SOURCE.json"))))
    shas = {f["id"]: f["sha256"] for f in src["files"] if f.get("sha256")}
    core = read_core(cfg)
    sel, _ = select_rule(pools, {c["upid"] for c in core}, {c["taxid"] for c in core}, cfg)
    write_manifest_block(manifest_entries(cfg, sel, shas))
    print(f"[download] {len(shas)} gap-fill FASTA checksums written to {MANIFEST}")


# ----------------------------------------------------------------------------------------------------------- assemble
def read_fasta_gz(path):
    """-> list of (accession, entry-name species suffix, sequence)."""
    out, acc, sfx, buf = [], None, None, []
    with gzip.open(path, "rt") as f:
        for line in f:
            if line.startswith(">"):
                if acc is not None:
                    out.append((acc, sfx, "".join(buf)))
                parts = line[1:].split()[0].split("|")
                acc, sfx, buf = parts[1], parts[2].rsplit("_", 1)[-1] if len(parts) > 2 else None, []
            else:
                buf.append(line.strip().upper())
    if acc is not None:
        out.append((acc, sfx, "".join(buf)))
    return out


def clade_label(rec, cfg):
    if rec is None:
        return "unknown"
    names = set(rec["linall"]) | {rec["name"]}
    return next((lab for n, lab in cfg["clade_labels"] if n in names), "unknown")


def assemble(cfg):
    meta, pools, core_meta = load_snapshot(cfg)
    sel_doc = json.load(open(os.path.join(RES_DIR, "panel_selection.json")))
    species = []
    for c in read_core(cfg):
        species.append({"upid": c["upid"], "taxid": c["taxid"], "code": c["code"], "name": c["name"], "source": "QfO_2026_02",
                        "group": "core", "fasta": P(os.path.join(cfg["core"]["fasta_dir"], f"{c['upid']}_{c['taxid']}.fasta.gz")),
                        "meta": core_meta.get(c["upid"])})
    for s in sel_doc["selected"]:
        species.append({"upid": s["upid"], "taxid": s["taxid"], "code": s["mnemonic"], "name": s["name"],
                        "source": f"gap_fill_UniProt_{cfg['uniprot_release']}", "group": s["clade"],
                        "fasta": P(os.path.join(cfg["gap_fill_fasta"]["dir"], f"{s['upid']}_{s['taxid']}.fasta.gz")),
                        "meta": pools.get(s["upid"])})
    out_fa, out_idx = P(cfg["panel"]["fasta"]), P(cfg["panel"]["index"])
    # species code: QfO oscode (core) / UniProt taxonomy mnemonic (gap-fill); entry-name suffix if missing;
    # 'TX<taxid>' when the mnemonic is a group code (starts with a digit) or already taken
    os.makedirs(os.path.dirname(out_fa), exist_ok=True)
    qc_sp, n_tot, n_empty, seen_codes = [], 0, 0, set()
    with open(out_fa, "w") as fa, open(out_idx, "w") as ix:
        ix.write("code\tindex\taccession\n")
        for sp in species:
            recs = read_fasta_gz(sp["fasta"])
            sfx = collections.Counter(x[1] for x in recs).most_common(1)[0][0]
            if not sp["code"]:
                sp["code"] = sfx                       # e.g. Daphnia magna has no oscode in the QfO list
            elif sp["code"] != sfx:
                print(f"[warn] {sp['upid']}: code {sp['code']} != entry-name suffix {sfx}")
            if not sp["code"] or sp["code"][0].isdigit() or sp["code"] in seen_codes:
                sp["code"] = f"TX{sp['taxid']}"        # UniProt group mnemonics (9ROSI, 9NEOP, ...) are not species-unique
            assert sp["code"] not in seen_codes, sp["code"]
            seen_codes.add(sp["code"])
            i = 0
            for acc, _, seq in recs:
                seq = seq.replace("*", "")
                if not seq:
                    n_empty += 1
                    continue
                fa.write(f">{sp['code']}|{i}\n")
                for k in range(0, len(seq), 60):
                    fa.write(seq[k:k + 60] + "\n")
                ix.write(f"{sp['code']}\t{i}\t{acc}\n")
                i += 1
            sp["n_proteins"] = i
            n_tot += i
            qc_sp.append({"code": sp["code"], "upid": sp["upid"], "n_proteins": i, "fasta_sha256": sha256_file(sp["fasta"])})
            print(f"[assemble] {sp['code']:6s} {sp['upid']} {i:6d} {sp['name'][:50]}")
    codes = [s["code"] for s in species]
    assert len(codes) == len(set(codes)), f"duplicate species codes: {[c for c, n in collections.Counter(codes).items() if n > 1]}"
    with open(P(cfg["panel"]["species_table"]), "w") as f:
        f.write("code\ttaxid\tname\tsource\tn_proteins\tclade\tupid\tselection_group\n")
        for s in species:
            f.write(f"{s['code']}\t{s['taxid']}\t{s['name']}\t{s['source']}\t{s['n_proteins']}\t{clade_label(s['meta'], cfg)}\t{s['upid']}\t{s['group']}\n")
    qc = {"n_species": len(species), "n_core": sum(1 for s in species if s["group"] == "core"),
          "n_gap_fill": sum(1 for s in species if s["group"] != "core"), "n_proteins": n_tot,
          "n_proteins_core": sum(s["n_proteins"] for s in species if s["group"] == "core"),
          "n_proteins_gap_fill": sum(s["n_proteins"] for s in species if s["group"] != "core"),
          "n_empty_sequences_skipped": n_empty,
          "clade_counts": dict(collections.Counter(clade_label(s["meta"], cfg) for s in species)),
          "n_species_without_lineage_metadata": sum(1 for s in species if s["meta"] is None),
          "panel_fasta_sha256": sha256_file(out_fa), "panel_species_tsv_sha256": sha256_file(P(cfg["panel"]["species_table"])),
          "species": qc_sp, "script": "scripts/data/build_panel.py assemble", "config_sha256": sha256_file(CFG_PATH)}
    with open(os.path.join(RES_DIR, "panel.json"), "w") as f:
        json.dump(qc, f, indent=1)
    print(f"[assemble] panel: {qc['n_species']} species ({qc['n_core']} core + {qc['n_gap_fill']} gap-fill), {n_tot} proteins -> {out_fa}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("step", choices=["snapshot", "select", "download", "assemble", "all"])
    ap.add_argument("--refresh", action="store_true", help="re-query the REST API even if a snapshot exists")
    args = ap.parse_args()
    cfg = load_cfg()
    if args.step in ("snapshot", "all"):
        snapshot(cfg, args.refresh)
    if args.step in ("select", "all"):
        select(cfg)
    if args.step in ("download", "all"):
        download(cfg)
    if args.step in ("assemble", "all"):
        assemble(cfg)


if __name__ == "__main__":
    main()

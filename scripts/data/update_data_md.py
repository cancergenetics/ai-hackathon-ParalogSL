#!/usr/bin/env python
"""Regenerate the dataset table in DATA.md from config/data_manifest.yaml + data/raw/<group>/SOURCE.json.
Only the region between the DATA_TABLE markers is rewritten (markers are inserted after the intro if missing).
Columns: name | source URL | version/date | SHA-256 | license | used for | committed?. Checksums come from SOURCE.json only (never hand-entered)."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from manifest_io import ROOT, RAW, load_manifest, group_of, read_json

START, END = "<!-- DATA_TABLE_START (generated by scripts/data/update_data_md.py; do not edit by hand) -->", "<!-- DATA_TABLE_END -->"
cell = lambda s: str(s).replace("|", "\\|").replace("\n", " ")


def main():
    entries = load_manifest()
    src_cache = {}
    rows, n_ok, n_man, n_fail = [], 0, 0, 0
    for e in entries:
        g = group_of(e)
        if g not in src_cache:
            src_cache[g] = read_json(os.path.join(RAW, g, "SOURCE.json"), {"files": []})
        rec = next((f for f in src_cache[g].get("files", []) if f["id"] == e["id"]), None)
        name = f"`{g}/{e['filename']}`" + ("" if g == e["id"] else f" ({e['id']})")
        url = e["url"]
        if rec and rec.get("sha256") and rec.get("status", "").startswith("ok"):
            n_ok += 1
            ver = (e.get("version") + "; " if e.get("version") else "") + "retrieved " + rec["date"][:10]
            if rec.get("status") == "ok_manual":
                ver += " (manual download)"
            sha = f"`{rec['sha256']}`"
            if rec.get("sha256_of"):
                sha += f" (of {rec['sha256_of']}, {rec['n_files']} files)"
            if rec.get("zip_member"):
                sha += " (extracted member)"
            sha += f" · {rec['bytes']:,} B"
        elif e.get("manual"):
            n_man += 1; ver, sha = "-", "**NOT OBTAINED: manual browser download needed** (see config/data_manifest.yaml notes)"
        else:
            n_fail += 1; ver, sha = "-", "**NOT OBTAINED: " + (rec.get("error", "not downloaded yet") if rec else "not downloaded yet")[:120] + "**"
        rows.append(f"| {cell(name)} | {cell(url)} | {cell(ver)} | {cell(sha)} | {cell(e['license'])} | {cell(e['used_for'])} | {cell(e['committed'])} |")
    table = "\n".join([
        "| name | source URL | version/date | SHA-256 | license | used for | committed? |",
        "|---|---|---|---|---|---|---|", *rows])
    summary = f"{len(entries)} manifest entries: {n_ok} obtained and checksummed, {n_man} need a manual browser download, {n_fail} failed/not yet downloaded."
    block = f"{START}\n\n{summary}\n\n{table}\n\n{END}"
    p = os.path.join(ROOT, "DATA.md")
    txt = open(p).read()
    if START in txt:
        txt = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, txt, flags=re.S)
    else:
        txt = txt.rstrip() + "\n\n" + block + "\n"
    open(p, "w").write(txt)
    print(summary)


if __name__ == "__main__":
    main()
